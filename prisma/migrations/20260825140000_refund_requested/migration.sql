-- Повернення грошей із кабінету.
--
-- Одна колонка, бо решта вже є: статус REFUNDED, refundedAt і сама обробка
-- події «reversed» лежать у Payment із першого дня платіжки — не вистачало
-- рівно того, хто про повернення попросить.
--
-- Навіщо окремий момент «попросили», якщо є refundedAt. Джерело правди про
-- гроші — вебхук банку, а не наша кнопка: між натисканням і підтвердженням
-- банку минає час, і весь цей час клуб має бачити «повернення в дорозі».
-- Без цієї колонки кабінет після натискання виглядав би точно так само, як
-- до нього, — і адміністратор натиснув би вдруге.

-- AlterTable
ALTER TABLE "Payment" ADD COLUMN     "refundRequestedAt" TIMESTAMP(3);
