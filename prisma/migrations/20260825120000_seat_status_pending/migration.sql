-- Нові стани місця в груповому занятті: PENDING (тримається під оплату) і
-- EXPIRED (не оплатили за відведений час).
--
-- Окрема міграція заради однієї причини: Postgres не дозволяє використати
-- щойно додане значення enum у тій самій транзакції, де його додали
-- ("unsafe use of new value of enum type"). Prisma виконує кожну міграцію
-- однією транзакцією, а наступна міграція будує частковий індекс саме по
-- 'PENDING' — тому додавання значень і їх використання рознесені по файлах.

-- AlterEnum
ALTER TYPE "SeatStatus" ADD VALUE 'PENDING';
ALTER TYPE "SeatStatus" ADD VALUE 'EXPIRED';
