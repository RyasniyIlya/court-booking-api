/**
 * Що клубу відкрито за його планом — одне місце, де це рахується.
 *
 * ── Головне правило: відсутність плану нічого не обмежує ──────────────────
 *
 * `planId = null` означає «оператор ще не призначив план», а не «нульовий
 * тариф». Усі клуби, заведені до появи планів, мають саме такий стан, і
 * якби null читався як «нічого не можна», міграція мовчки вимкнула б
 * половину кабінету в тих, хто вже платить і працює. Обмежує ТІЛЬКИ
 * призначений план.
 *
 * ── Чому прапорці, а не рівень-число ─────────────────────────────────────
 *
 * Спокуса написати `tier >= 2` велика, але вона ламається на першому ж
 * клубі, якому потрібна аналітика без групових занять. `tier` лишився для
 * сортування й підпису; рішення ухвалюють булеві поля плану.
 *
 * ── Чому не блокуємо доступ до вже створених даних ───────────────────────
 *
 * Клуб міг завести тренерів на другому плані, а потім перейти на перший.
 * Його тренери й розклад нікуди не діваються: план закриває СТВОРЕННЯ і
 * РЕДАГУВАННЯ, а не читання. Забрати клубу видимість його ж даних за
 * гроші — це той крок, після якого пишуть у профільні чати, і рівно та
 * сама логіка, що вже діє для простроченої оплати (див. lib/billing.ts:
 * кабінет не блокується, вимикається лише онлайн-запис).
 */

export type PlanFeatures = {
  /** Тренери: картки, ціни, прив'язка до броні */
  trainers: boolean;
  /** Групові заняття й продаж місць */
  groups: boolean;
  /** Поглиблена аналітика і картотека клієнтів */
  analytics: boolean;
};

/** Усе відкрито. Стан клубу без призначеного плану. */
export const ALL_FEATURES: PlanFeatures = {
  trainers: true,
  groups: true,
  analytics: true,
};

type PlanLike = {
  featTrainers: boolean;
  featGroups: boolean;
  featAnalytics: boolean;
} | null | undefined;

/**
 * Права клубу за планом.
 *
 * Приймає сам план, а не клуб: так функцію видно з тестів і з консолі, і
 * вона не тягне за собою форму запиту до бази.
 */
export function planFeatures(plan: PlanLike): PlanFeatures {
  if (!plan) return ALL_FEATURES;

  return {
    trainers: plan.featTrainers,
    groups: plan.featGroups,
    analytics: plan.featAnalytics,
  };
}

/**
 * Скільки платить конкретний клуб за період, копійки.
 *
 * Індивідуальна ціна б'є ціну плану — продаємо поштучно, і домовленості
 * різні. `0` — валідна ціна (безкоштовне впровадження, перший клуб у місті),
 * тому перевірка саме на null/undefined, а не на істинність.
 */
export function clubPrice(
  plan: { price: number } | null | undefined,
  override: number | null | undefined,
): number | null {
  if (override !== null && override !== undefined) return override;
  return plan?.price ?? null;
}

