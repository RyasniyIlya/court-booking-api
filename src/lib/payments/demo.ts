/**
 * Чи працює тестова платіжка.
 *
 * Провайдер `mock` — це явний вибір клубу в налаштуваннях, підписаний
 * «заглушка для перевірки · без грошей». Він працює скрізь, де клуб сам
 * його обрав, включно з production: це потрібно для демо на прототипі.
 * Справжні гроші не рухаються, а сторінка оплати має помітне попередження.
 *
 * DEMO_PAYMENTS=false — аварійний вимикач: закриває mock повністю в усіх
 * середовищах. Будь-яке інше значення (у тому числі порожнє) дозволяє його.
 *
 * Справжніх провайдерів (mono, LiqPay) це не стосується взагалі.
 */
export function mockPaymentsEnabled(): boolean {
  return process.env.DEMO_PAYMENTS !== 'false';
}
