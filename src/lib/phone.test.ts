import { describe, it, expect } from 'vitest';
import { normalizePhone, isSearchableTail } from './phone';

/**
 * Один номер — одне представлення в базі. Якщо ця нормалізація розійдеться,
 * «067 123 45 67» і «+380671234567» стануть двома різними картками клієнта,
 * і клуб побачить двох людей замість одної.
 */
describe('normalizePhone', () => {
  const SAME = '+380671234567';

  it.each([
    ['+380671234567', 'уже E.164'],
    ['380671234567', 'без плюса'],
    ['0671234567', 'національний з нулем'],
    ['671234567', 'без нуля й коду'],
    ['00380671234567', 'міжнародний префікс 00'],
    ['067 123 45 67', 'з пробілами'],
    ['(067) 123-45-67', 'з дужками й дефісами'],
    ['+38 (067) 123 45 67', 'усе разом'],
  ])('%s -> той самий номер (%s)', (input) => {
    expect(normalizePhone(input)?.e164).toBe(SAME);
  });

  it('хвіст — сім останніх цифр, за ними шукає ресепшен', () => {
    expect(normalizePhone('0671234567')?.tail).toBe('1234567');
  });

  it('гарний вигляд для адміністратора', () => {
    expect(normalizePhone('+380671234567')?.pretty).toBe('067 123 45 67');
  });

  it('іноземний номер проходить, якщо є плюс', () => {
    const r = normalizePhone('+48123456789');
    expect(r?.e164).toBe('+48123456789');
    // Не український — форматувати як 0XX не можна
    expect(r?.pretty).toBe('+48123456789');
  });

  it('іноземний БЕЗ плюса не вгадуємо', () => {
    // Без коду країни це так само схоже на місцевий номер із помилкою
    expect(normalizePhone('48123456789')).toBeNull();
  });

  it.each([
    ['', 'порожній рядок'],
    ['   ', 'самі пробіли'],
    ['абв', 'без цифр'],
    ['123', 'закоротко'],
    ['+1', 'плюс і одна цифра'],
    ['+1234567890123456', 'задовго навіть для E.164'],
  ])('%s -> null (%s)', (input) => {
    expect(normalizePhone(input)).toBeNull();
  });
});

describe('isSearchableTail', () => {
  it('чотири цифри — уже можна шукати', () => {
    expect(isSearchableTail('4567')).toBe(true);
  });

  it('три цифри — ще ні: пів клубу під такий хвіст підійде', () => {
    expect(isSearchableTail('456')).toBe(false);
  });

  it('рахує саме цифри, не символи', () => {
    expect(isSearchableTail('45-67')).toBe(true);
  });

  it('довше за номер — не хвіст', () => {
    expect(isSearchableTail('12345678901')).toBe(false);
  });
});
