import bcrypt from 'bcryptjs';

import { prisma } from './db';

/**
 * Зміна пароля кабінету з привʼязаного чату.
 *
 * Це і є те, що в інших продуктах називають «забули пароль», але без
 * листа й одноразового посилання: доказом особи тут працює сам чат.
 * Привʼязати його можна лише двома шляхами — /login з паролем або код із
 * кабінету, — тож чат, який уже привʼязаний, колись пароль знав. Цього
 * досить, щоб дозволити задати новий.
 *
 * УВАГА: непривʼязаному чату ця команда не допоможе принципово. Telegram
 * дає нам номер чату, а не особу: «скинь пароль ось цій пошті» від
 * будь-кого перетворило б бота на довідник «хто з цією поштою у нас є»
 * плюс кнопку «зламати клуб». Той, хто і пароль забув, і бота не
 * підключив, лишається на операторові платформи — інакше не буває.
 *
 * Межі пароля дзеркалять routes/admin/auth.ts (8..128): бот не має
 * пускати те, чого потім не прийме форма входу в кабінет.
 */

/** Ті самі межі, що й у схемі реєстрації. */
export const MIN_LEN = 8;
export const MAX_LEN = 128;

/**
 * Розібрати «/newpassword новий пароль».
 *
 * Пароль може містити пробіли — склеюємо все назад тим самим правилом,
 * що й parseLogin. Різниця одна: тут немає пошти, тобто весь хвіст
 * команди і є пароль.
 */
export function parseNewPassword(args: string[]): string | null {
  const password = args.join(' ').trim();
  return password ? password : null;
}

/** Чому пароль не годиться, або null, якщо годиться. */
export function passwordProblem(password: string): string | null {
  if (password.length < MIN_LEN) return `Пароль закороткий — треба щонайменше ${MIN_LEN} символів.`;
  if (password.length > MAX_LEN) return `Пароль задовгий — не більше ${MAX_LEN} символів.`;
  return null;
}

/**
 * Задати новий пароль власникові цього чату.
 *
 * Повертає готовий текст відповіді: рішення «що сказати людині» лишається
 * тут разом із рішенням «чи можна», інакше botHandlers довелося б знати
 * про кожну причину відмови окремо.
 */
export async function changePassword(chatId: string, password: string): Promise<string> {
  const user = await prisma.user.findUnique({
    where: { tgChatId: chatId },
    select: { id: true, email: true },
  });

  /* Сюди доходять і непривʼязані чати: повідомлення з паролем ми стираємо
     ДО перевірки, тож відповісти все одно треба. */
  if (!user) {
    return [
      'Цей чат не привʼязаний до жодного акаунта, тому міняти пароль нема кому.',
      '',
      'Якщо пароль від кабінету втрачено і бот теж не підключений —',
      'звертайтесь до нас: відновити доступ можемо тільки ми.',
    ].join('\n');
  }

  const problem = passwordProblem(password);
  if (problem) return problem;

  /* Вартість 12 — як у реєстрації (routes/admin/auth.ts). Саме нею
     створюється пароль, який людина вводить руками, і здешевлювати його
     тут не можна: хеш той самий, вхід той самий. */
  const passwordHash = await bcrypt.hash(password, 12);
  await prisma.user.update({ where: { id: user.id }, data: { passwordHash } });

  return [
    '✅ Пароль змінено',
    `Кабінет: <code>${user.email}</code>`,
    '',
    '<i>Повідомлення з паролем я вже видалив.</i>',
    '<i>PIN модератора і власника лишились попередні — вони міняються в кабінеті.</i>',
  ].join('\n');
}

/* ── Заявка оператору ─────────────────────────────────────────────────── */

/**
 * «Забув пароль» від того, кому /newpassword не допоможе.
 *
 * Той, чий чат не привʼязаний, довести свою особу боту не може — і не
 * зможе ніколи — тому єдиний чесний шлях лишається людський: заявка,
 * дзвінок, оператор. Бот тут не відновлює доступ, а лише кладе заявку
 * в чергу і показує оператору, з ким саме говорити.
 *
 * Відповідь однакова і на відому пошту, і на невідому. Інакше команда
 * перетворюється на перевірку «чи є такий клуб у системі», доступну
 * будь-кому з Telegram.
 */
const REQUEST_SENT = [
  '📨 Заявку прийнято.',
  '',
  'Якщо така пошта є в системі, ми звʼяжемось із вами найближчим часом і задамо новий пароль після перевірки.',
  '',
  '<i>Пароль у чат не приходить: його диктує оператор особисто.</i>',
].join('\n');

/** Скільки заявок від одного чату приймаємо, поки перша не закрита. */
const MAX_OPEN = 3;

export async function requestReset(
  chatId: string,
  email: string,
  tgName: string | null,
): Promise<string> {
  const clean = email.trim().toLowerCase();
  if (!clean.includes('@')) return 'Формат: <code>/restore ваша-пошта@приклад.com</code>';

  const user = await prisma.user.findUnique({
    where: { email: clean },
    select: { id: true, clubId: true },
  });

  /* Немає акаунта — мовчки той самий текст. Заявку не створюємо: черга
     оператора не має заповнюватись вигаданими адресами. */
  if (!user) return REQUEST_SENT;

  /* Одна людина, що тисне команду десять разів поспіль, не має
     перетворити чергу на десять однакових рядків. */
  const open = await prisma.passwordReset.count({
    where: { userId: user.id, status: 'PENDING' },
  });
  if (open >= MAX_OPEN) return REQUEST_SENT;

  await prisma.passwordReset.create({
    data: {
      clubId: user.clubId,
      userId: user.id,
      email: clean,
      tgChatId: chatId,
      tgName,
    },
  });

  return REQUEST_SENT;
}
